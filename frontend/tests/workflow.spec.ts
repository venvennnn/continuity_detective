import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'

test('real sequence: reference, playback findings, forward change, undo, resume and export', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.locator('.shot-card')).toHaveCount(3)
  const video = page.getByTestId('sequence-player').locator('video')
  await expect(video).toBeVisible({ timeout: 60000 })
  await expect.poll(() => video.evaluate(v => (v as HTMLVideoElement).duration)).toBe(24)
  await expect(page.locator('.finding-card')).toHaveCount(0)
  await page.getByRole('button', { name: 'Review reference' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Use this reference', exact: true }).click()
  await expect(page.locator('.findings-summary')).toContainText('34 flagged samples', { timeout: 60000 })
  await expect(page.locator('.finding-card')).toHaveCount(2)
  await page.locator('.finding-main').nth(1).click()
  await expect.poll(() => video.evaluate(v => (v as HTMLVideoElement).currentTime)).toBe(16)
  await expect(page.locator('.video-annotation.flagged')).toContainText('take3.mp4')
  await page.getByRole('button', { name: 'Evidence A/B', exact: true }).click()
  await expect(page.locator('.evidence-card')).toHaveCount(2)
  await expect(page.locator('.evidence-card').nth(1)).toContainText('take3.mp4')
  await page.getByRole('button', { name: 'Sequence playback', exact: true }).click()
  await page.locator('.finding-main').first().click()
  await page.getByRole('button', { name: 'New wardrobe from here' }).click()
  await expect(page.getByRole('dialog')).toContainText('take2.mp4')
  await page.getByRole('button', { name: 'Confirm new reference', exact: true }).click()
  await expect(page.locator('.findings-summary')).toContainText('17 flagged samples', { timeout: 60000 })
  await expect(page.locator('.finding-card')).toHaveCount(1)
  await expect(page.locator('.finding-main')).toContainText('take3.mp4')
  await expect(page.locator('.reference-summary')).toContainText('2 reference segments')
  await page.getByRole('button', { name: 'Undo change', exact: true }).click()
  await expect(page.locator('.findings-summary')).toContainText('34 flagged samples')
  await page.locator('.finding-main').first().click()
  await page.getByLabel('Region assessment').selectOption('occluded')
  await expect(page.locator('.findings-summary')).toContainText('33 flagged samples')
  await expect(page.locator('.findings-summary')).toContainText('1 not assessable')
  await page.getByLabel('Region assessment').selectOption('')
  await page.getByLabel('Decision', { exact: true }).selectOption('intentional')
  await expect(page.locator('.findings-summary')).toContainText('33 flagged samples')
  await expect(page.locator('.save-status')).toContainText('Saved locally')
  const analysisCalls: string[] = []
  page.on('request', req => { if (req.url().includes('/analysis-runs')) analysisCalls.push(req.url()) })
  await page.reload()
  await expect(page.locator('.findings-summary')).toContainText('33 flagged samples')
  expect(analysisCalls).toHaveLength(0)
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export evidence JSON' }).click()
  const download = await downloading
  const path = await download.path()
  const output = JSON.parse(await fs.readFile(path!, 'utf-8'))
  expect(output.clips).toHaveLength(3)
  expect(output.reference_events.length).toBeGreaterThanOrEqual(3)
  expect(output.findings.some((f: { superseded: boolean }) => f.superseded)).toBeTruthy()
  expect(output.findings[0].reference_evidence.thumbnail).toMatch(/^data:image/)
  expect(output.findings.some((f: { human_review?: { decision?: string } }) => f.human_review?.decision === 'intentional')).toBeTruthy()
  await page.locator('.finding-main').last().click()
  await page.screenshot({ path: 'test-results/workbench-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/workbench-mobile.png', fullPage: true })
  await page.route('**/api/**', route => route.abort())
  await page.reload()
  await expect(page.locator('.findings-summary')).toContainText('33 flagged samples')
  await expect.poll(() => page.locator('.evidence-mini-grid img').first().evaluate(img => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  expect(errors).toEqual([])
})

test('correcting the initial reference keeps coverage from sequence start', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Review reference' }).click()
  await page.getByRole('button', { name: 'Use this reference', exact: true }).click()
  await expect(page.locator('.findings-summary')).toContainText('34 flagged samples', { timeout: 60000 })
  await page.getByRole('button', { name: 'Edit reference', exact: true }).click()
  await page.getByRole('button', { name: 'Select take1.mp4 at 00:01.000', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm new reference', exact: true }).click()
  await expect(page.locator('.findings-summary')).toContainText('34 flagged samples', { timeout: 60000 })
  await expect(page.getByRole('alert')).toHaveCount(0)
  // Save transactions may complete after the current results become visible.
  await expect(page.locator('.save-status')).toContainText('Saved locally')
  const saved = await page.evaluate(async () => {
    return await new Promise<{start_ms:number;start_clip_id:string}>((resolve,reject) => {
      const request=indexedDB.open('continuity-detective',1)
      request.onsuccess=()=>{const db=request.result;const get=db.transaction('project').objectStore('project').get('last');get.onsuccess=()=>{resolve(get.result.references[0]);db.close()};get.onerror=()=>reject(get.error)}
    })
  })
  expect(saved.start_ms).toBe(0)
  expect(saved.start_clip_id).toBe('clip-0')
})
